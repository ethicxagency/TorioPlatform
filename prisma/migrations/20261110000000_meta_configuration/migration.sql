-- Super Admin managed Meta app configuration. Additive only; NULL columns fall back to environment variables.
CREATE TABLE "meta_configuration" (
  "id" TEXT NOT NULL DEFAULT 'default',
  "appName" TEXT,
  "appId" TEXT,
  "appSecretCiphertext" TEXT,
  "apiVersion" TEXT,
  "businessId" TEXT,
  "appMode" TEXT,
  "appDomain" TEXT,
  "websiteUrl" TEXT,
  "oauthRedirectUri" TEXT,
  "allowedRedirectUris" TEXT[] DEFAULT ARRAY[]::TEXT[],
  "oauthStateTtlMinutes" INTEGER,
  "allowedDomains" TEXT[] DEFAULT ARRAY[]::TEXT[],
  "successUrl" TEXT,
  "failureUrl" TEXT,
  "webhookBaseUrl" TEXT,
  "webhookEnabled" BOOLEAN,
  "verifyTokenCiphertext" TEXT,
  "whatsappConfigId" TEXT,
  "discoverWhatsapp" BOOLEAN,
  "messengerEnabled" BOOLEAN NOT NULL DEFAULT true,
  "instagramEnabled" BOOLEAN NOT NULL DEFAULT true,
  "whatsappEnabled" BOOLEAN NOT NULL DEFAULT true,
  "lastWebhookVerifiedAt" TIMESTAMP(3),
  "lastKeyRotationAt" TIMESTAMP(3),
  "updatedById" UUID,
  "updatedByEmail" TEXT,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "meta_configuration_pkey" PRIMARY KEY ("id")
);
